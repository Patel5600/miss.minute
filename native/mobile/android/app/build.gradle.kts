// The web layer (overlay.html and dashboard.html) is generated by 'npm run build:mobile' and is not committed.
val checkWebAssets by tasks.registering {
    val webDir = layout.projectDirectory.dir("src/main/assets/web")
    doLast {
        val missing = listOf("overlay.html", "dashboard.html").any { !webDir.file(it).asFile.exists() }
        if (missing) {
            throw GradleException("Run npm run build:mobile first (needs Node 22)")
        }
    }
}
tasks.matching { it.name == "preBuild" }.configureEach { dependsOn(checkWebAssets) }

